import {build} from 'esbuild';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const result=await build({entryPoints:[fileURLToPath(new URL('../src/coach.worker.ts',import.meta.url))],bundle:true,write:false,format:'iife',platform:'browser',target:'es2022',minify:true});
writeFileSync(new URL('../src/coachWorkerSource.ts',import.meta.url),'// Generated by scripts/build-coach-worker.mjs; do not edit by hand.\nexport default '+JSON.stringify(result.outputFiles[0].text)+';\n');
console.log('Inline coach worker regenerated.');
